#!/usr/bin/env python3
"""Generate src/params_table.h from the stock firmware's parameter table.

The stock table (flash 0xECF0, 185 x 32-byte records) defines the EEPROM payload
layout, so the rewrite must reproduce its order, sizes and flags exactly. We emit an
X-macro list that the C code expands into the params_t struct, the descriptor table
and typed defaults.

usage: gen_params.py STOCK_FW.bin OUT.h
"""
import struct, sys

TABLE_START, TABLE_COUNT = 0xECF0, 185

C_TYPE = {1: 'bool', 2: 'uint8_t', 3: 'uint16_t', 4: 'uint32_t', 5: 'int8_t',
          6: 'int16_t', 7: 'int32_t', 8: 'float', 13: 'uint8_t'}
PT_NAME = {1: 'PT_BOOL', 2: 'PT_U8', 3: 'PT_U16', 4: 'PT_U32', 5: 'PT_I8', 6: 'PT_I16',
           7: 'PT_I32', 8: 'PT_FLOAT', 10: 'PT_STRING', 12: 'PT_RESERVED', 13: 'PT_ENUM'}


def cstr(fw, a):
    return fw[a:fw.find(b'\0', a)].decode('latin1') if 0 < a < len(fw) else ''


def enum_names(fw, addr):
    out = []
    while addr and (a := struct.unpack_from('<I', fw, addr + 4 * len(out))[0]):
        out.append(cstr(fw, a))
    return out


def c_default(fw, typ, size, dflt, enum):
    if typ == 1:
        return 'true' if dflt == 'true' else 'false'
    if typ == 8:
        v = float(dflt or 0)
        return f'{v!r}f'
    if typ == 13:
        names = enum_names(fw, enum)
        return str(names.index(dflt)) if dflt in names else (dflt or '0')
    if typ == 10:
        return '"' + dflt.replace('"', '\\"') + '"'
    if typ == 12:
        return '0'
    return dflt or '0'


def main(fw_path, out_path):
    fw = open(fw_path, 'rb').read()
    lines, enums, reserved = [], {}, 0
    for i in range(TABLE_COUNT):
        typ, ram, name, dflt, w4, w5, desc, enum = struct.unpack_from('<8I', fw, TABLE_START + 32 * i)
        size, flags = w4 & 0xff, (w4 >> 8) & 0xff
        n, dv = cstr(fw, name), cstr(fw, dflt)
        if typ == 12:
            field = f'reserved{reserved}'
            reserved += 1
        else:
            field = n.replace('.', '_')
        if typ == 13 and enum:
            enums[enum] = enum_names(fw, enum)
        ctype = C_TYPE.get(typ, 'char') if typ != 10 else 'char'
        lines.append(f'    P({field:28s}, "{n}", {PT_NAME[typ]:11s}, {ctype:8s}, {size:3d}, '
                     f'{flags:#04x}, {c_default(fw, typ, size, dv, enum)}, '
                     f'{"enum_" + format(enum, "x") if typ == 13 else "NULL"}, "") \\')  # descriptions: the stock text is not copied
    with open(out_path, 'w') as f:
        f.write('/* GENERATED by tools/gen_params.py from the stock firmware table @0xECF0.\n'
                ' * Do not edit: order, sizes and flags define the EEPROM payload layout\n'
                ' * (stock cparam.c, 551 stored bytes). */\n#pragma once\n\n')
        for addr, names in enums.items():
            f.write(f'#define ENUM_{addr:X}_COUNT {len(names)}\n')
        f.write('\n/* P(field, name, ptype, ctype, size, flags, default, enum, description)\n'
                ' * flags bit0 = runtime only (not stored), bit1 = factory calibration */\n'
                '#define PARAM_LIST(P) \\\n' + '\n'.join(lines) + '\n\n')
        for addr, names in enums.items():
            f.write(f'#define ENUM_{addr:X}_NAMES ' + ', '.join(f'"{x}"' for x in names) + '\n')
    print(f'{out_path}: {TABLE_COUNT} parameters, {len(enums)} enums')


if __name__ == '__main__':
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(*sys.argv[1:])
